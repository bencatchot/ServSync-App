-- Disposable local foundation ONLY. Not a migration for an existing ServSync project.
-- The production identity bridge and installation/credentials remain unimplemented.
begin;
do $$ begin
  if current_database() !~ '^servsync_practice_local_[a-f0-9]+$'
     or exists (select 1 from pg_namespace where nspname in ('auth', 'storage'))
     or to_regclass('public.contractor_profiles') is not null then
    raise exception 'Requires an empty dedicated disposable Practice database';
  end if;
end $$;
create role practice_app nologin;
create role practice_cleanup nologin;
create schema practice;
revoke all on schema practice from public;
grant usage on schema practice to practice_app, practice_cleanup;
create table practice.environment (purpose text primary key check (purpose = 'disposable-local-practice'));
insert into practice.environment values ('disposable-local-practice');
create table practice.owners (contractor_id uuid primary key, owner_id uuid not null, enabled boolean not null default true);
create function practice.actor() returns uuid language sql stable as $$
  select nullif(current_setting('practice.actor_id', true), '')::uuid
$$;
alter table practice.owners enable row level security;
alter table practice.owners force row level security;
create policy own_binding on practice.owners to practice_app using (owner_id=practice.actor());
create function practice.owns(contractor uuid) returns boolean language sql stable as $$
  select exists(select 1 from practice.owners where contractor_id = contractor and owner_id = practice.actor() and enabled)
$$;
grant select on practice.environment, practice.owners to practice_app;
create table practice.workspaces (
  id uuid primary key default gen_random_uuid(), contractor_id uuid not null references practice.owners,
  created_at timestamptz not null default clock_timestamp(),
  expires_at timestamptz not null default clock_timestamp() + interval '720 hours',
  snapshot jsonb not null check (octet_length(snapshot::text) <= 1048576),
  revision integer not null default 1,
  check (expires_at > created_at and expires_at <= created_at + interval '720 hours 1 second')
);
create table practice.drafts (
  id uuid primary key, workspace_id uuid not null references practice.workspaces on delete cascade,
  revision integer not null default 1, payload jsonb not null check (octet_length(payload::text) <= 1048576),
  unique (workspace_id, id)
);
-- Generated bytes are owned by this cycle: no shared/source file paths or remote deletion targets.
create table practice.files (
  id uuid primary key, workspace_id uuid not null references practice.workspaces on delete cascade,
  bytes bytea not null check (octet_length(bytes) between 1 and 5242880),
  mime_type text not null check (mime_type = 'application/pdf')
);
create table practice.transfers (
  id uuid primary key, workspace_id uuid not null, draft_id uuid not null,
  draft_revision integer not null, package_hash text not null check (package_hash ~ '^[a-f0-9]{64}$'),
  payload jsonb check (octet_length(payload::text) <= 1048576),
  total_cents bigint not null check (total_cents between 0 and 100000000),
  expires_at timestamptz not null, status text not null default 'review' check(status in ('review', 'committing', 'complete', 'cancelled')),
  destination_id uuid,
  foreign key(workspace_id, draft_id) references practice.drafts(workspace_id, id) on delete cascade
);
create index on practice.drafts(workspace_id);
create index on practice.files(workspace_id);
create index on practice.transfers(workspace_id);
create index on practice.workspaces(contractor_id, expires_at);

alter table practice.workspaces enable row level security;
alter table practice.workspaces force row level security;
create policy owner_workspace on practice.workspaces to practice_app
  using (practice.owns(contractor_id)) with check (practice.owns(contractor_id));
do $$ declare t text; begin
  foreach t in array array['drafts', 'files', 'transfers'] loop
    execute format('alter table practice.%I enable row level security', t);
    execute format('alter table practice.%I force row level security', t);
    execute format('create policy owner_rows on practice.%I to practice_app using (exists(select 1 from practice.workspaces w where w.id = workspace_id)) with check (exists(select 1 from practice.workspaces w where w.id = workspace_id))', t);
  end loop;
end $$;
-- Readers cannot see expired payloads. Gateway uses status-only workspace metadata after expiry.
-- No browser database credential is issued; the local fixture gateway sets actor context.
grant select on practice.workspaces, practice.drafts, practice.files, practice.transfers to practice_app;
grant insert(id, contractor_id, snapshot) on practice.workspaces to practice_app;
grant update(snapshot, revision) on practice.workspaces to practice_app;
grant insert on practice.drafts, practice.files, practice.transfers to practice_app;
grant update(payload, revision) on practice.drafts to practice_app;
grant update(status, payload, destination_id) on practice.transfers to practice_app;

create function practice.guard_workspace() returns trigger language plpgsql as $$
begin
  -- Serialize starts/refreshes, so two clients cannot exceed a cycle quota.
  perform pg_advisory_xact_lock(hashtextextended(new.contractor_id::text, 0));
  if tg_op = 'INSERT' then
    new.expires_at := new.created_at + interval '720 hours';
    if exists(select 1 from practice.workspaces where contractor_id = new.contractor_id and expires_at > clock_timestamp()) then raise exception 'An active Practice cycle already exists'; end if;
    if (select count(*) from practice.workspaces where contractor_id = new.contractor_id) >= 2 then raise exception 'Practice storage limit reached; expired-cycle cleanup needs operator review'; end if;
    if exists(select 1 from practice.transfers t join practice.workspaces w on w.id=t.workspace_id where w.contractor_id=new.contractor_id and t.status='committing') then raise exception 'Resolve the pending transfer before starting again'; end if;
  elsif old.expires_at <= clock_timestamp() then raise exception 'Practice cycle expired';
  end if;
  return new;
end $$;
create trigger guard_workspace before insert or update on practice.workspaces for each row execute function practice.guard_workspace();

create function practice.guard_child() returns trigger language plpgsql as $$
declare w practice.workspaces; n bigint; reconciling boolean := false;
begin
  select * into w from practice.workspaces where id=new.workspace_id for update;
  if not found then raise exception 'Practice workspace unavailable'; end if;
  -- Completion/cancellation can reconcile a pending transfer after the cycle expired.
  if tg_table_name='transfers' and tg_op='UPDATE' then
    reconciling := old.status='committing' and new.status in ('complete','cancelled');
    if old.status in ('complete','cancelled') then raise exception 'Transfer is terminal'; end if;
    if old.status='review' and new.status='committing' then
      if old.expires_at<=clock_timestamp() or not exists(select 1 from practice.drafts where id=old.draft_id and workspace_id=w.id and revision=old.draft_revision) then raise exception 'Transfer review is stale'; end if;
    elsif not reconciling and not (old.status='review' and new.status='cancelled') then raise exception 'Invalid transfer transition'; end if;
    if new.status in ('complete','cancelled') and new.payload is not null then raise exception 'Terminal transfers must discard payloads'; end if;
    if new.status='complete' and new.destination_id is null then raise exception 'Receipt destination required'; end if;
  end if;
  if not reconciling then
    if w.expires_at <= clock_timestamp() then raise exception 'Practice cycle expired'; end if;
  end if;
  if tg_op='INSERT' then
    if tg_table_name='drafts' then
      select count(*) into n from practice.drafts where workspace_id=w.id;
      if n >= 50 then raise exception 'Practice Draft quota reached'; end if;
    elsif tg_table_name='files' then
      select count(*) into n from practice.files where workspace_id=w.id;
      if n >= 10 or (select coalesce(sum(octet_length(bytes)),0) from practice.files where workspace_id=w.id) + octet_length(new.bytes) > 20971520 then raise exception 'Practice generated-file quota reached'; end if;
    elsif tg_table_name='transfers' then
      if new.status <> 'review' or new.destination_id is not null or new.payload is null then raise exception 'Transfers must begin with a review'; end if;
      select count(*) into n from practice.transfers where workspace_id=w.id;
      if n >= 20 then raise exception 'Practice transfer quota reached'; end if;
      if new.expires_at > least(w.expires_at, clock_timestamp()+interval '10 minutes') then raise exception 'Review expiry exceeds cycle/review limit'; end if;
    end if;
  end if;
  return new;
end $$;
create trigger guard_draft before insert or update on practice.drafts for each row execute function practice.guard_child();
create trigger guard_file before insert on practice.files for each row execute function practice.guard_child();
create trigger guard_transfer before insert or update on practice.transfers for each row execute function practice.guard_child();

-- Cleanup is a narrow private capability, not a role with arbitrary row-delete access.
-- These two owner-run functions are the only elevation; fixed search paths and explicit
-- disposable-target/expiry/transfer checks are mandatory. No browser can execute them.
create function practice.cleanup_plan() returns table(workspace_id uuid, expires_at timestamptz, draft_count bigint, file_count bigint, file_bytes bigint, blocked boolean)
language sql security definer set search_path=pg_catalog,practice as $$
  select w.id, w.expires_at,
    (select count(*) from practice.drafts where workspace_id=w.id),
    (select count(*) from practice.files where workspace_id=w.id),
    (select coalesce(sum(octet_length(bytes)),0) from practice.files where workspace_id=w.id),
    exists(select 1 from practice.transfers where workspace_id=w.id and (status='committing' or (status='review' and expires_at>clock_timestamp())))
  from practice.workspaces w where w.expires_at <= clock_timestamp()
$$;
create function practice.cleanup_disposable(expected_database text, target uuid, expected_expiry timestamptz) returns boolean
language plpgsql security definer set search_path=pg_catalog,practice as $$
declare w practice.workspaces;
begin
  if current_database() <> expected_database or current_database() !~ '^servsync_practice_local_[a-f0-9]+$'
    or not exists(select 1 from practice.environment where purpose='disposable-local-practice') then raise exception 'Cleanup target mismatch'; end if;
  select * into w from practice.workspaces where id=target for update;
  if not found then return false; end if;
  if w.expires_at <> expected_expiry or w.expires_at > clock_timestamp() then raise exception 'Cleanup target changed or is not expired'; end if;
  if exists(select 1 from practice.transfers where workspace_id=w.id and (status='committing' or (status='review' and expires_at>clock_timestamp()))) then raise exception 'Active transfer blocks cleanup'; end if;
  delete from practice.workspaces where id=w.id;
  return true;
end $$;
revoke execute on all functions in schema practice from public;
grant execute on function practice.actor(), practice.owns(uuid), practice.guard_workspace(), practice.guard_child() to practice_app;
grant execute on function practice.cleanup_plan(), practice.cleanup_disposable(text,uuid,timestamptz) to practice_cleanup;
commit;
